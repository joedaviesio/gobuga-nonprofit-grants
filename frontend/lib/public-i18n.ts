const DICTIONARIES: Record<string, Dictionary> = { en, ro, ru };

/** Each language's own name, for the language links. */
export const LANGUAGE_NAMES: Record<string, string> = { en: "English", ro: "Română", ru: "Русский" };

export function hasDictionary(lang: string): boolean {
  return Object.prototype.hasOwnProperty.call(DICTIONARIES, lang);
}

export interface LangChoice {
  lang: string;            // the language to render
  defaultLang: string;     // the country's default for the public pages
  available: string[];     // the country's UI languages we have text for
  carry: string | null;    // `lang=` value for internal links; null for the default
}

/**
 * The page language: the requested one if the country offers it and we have
 * text for it, else the country's content language, else English.
 */
export function chooseLang(
  requested: string | null | undefined,
  contentLanguage: string | null | undefined,
  uiLanguages: readonly string[] | null | undefined,
): LangChoice {
  const offered = (uiLanguages ?? []).filter(hasDictionary);
  const defaultLang = contentLanguage && hasDictionary(contentLanguage)
    ? contentLanguage
    : offered[0] ?? "en";
  const available = offered.includes(defaultLang) ? offered : [defaultLang, ...offered];
  const lang = requested && available.includes(requested) ? requested : defaultLang;
  return { lang, defaultLang, available, carry: lang === defaultLang ? null : lang };
}

/** The text for `key` in `lang` (English if missing), with `{name}` filled in. */
export function t(lang: string, key: PublicKey, params: Record<string, string | number> = {}): string {
  const dict = DICTIONARIES[lang] ?? en;
  let text = dict[key] ?? en[key] ?? key;
  for (const [name, value] of Object.entries(params)) {
    text = text.split(`{${name}}`).join(String(value));
  }
  return text;
}

/** Every key, for the completeness test. */
export function dictionaryKeys(lang: string): string[] {
  return Object.keys(DICTIONARIES[lang] ?? {});
}
